'use client';

// Ask: questions about alerts in plain language, answered by a Cortex Agent that uses Cortex
// Analyst over the ALERTS_SV semantic view.
import { Send } from 'lucide-react';
import { useState } from 'react';
import { Reasoning } from '@/components/Reasoning';
import { Card, ErrorBox, Markdown, PoweredBy, SampleAiBadge } from '@/components/ui';
import { SAMPLE_QUESTIONS, ask } from '@/lib/client';
import type { AiText } from '@/lib/types';

export default function AskPage() {
  const [q, setQ] = useState('');
  const [turns, setTurns] = useState<{ q: string; a?: AiText; error?: string }[]>([]);
  const busy = turns.length > 0 && !turns[turns.length - 1].a && !turns[turns.length - 1].error;
  const go = (question: string) => {
    if (!question.trim() || busy) return;
    setQ('');
    setTurns((t) => [...t, { q: question }]);
    ask(question).then((a) => setTurns((t) => t.map((x, i) => (i === t.length - 1 ? { ...x, a } : x))),
      (e) => setTurns((t) => t.map((x, i) => (i === t.length - 1 ? { ...x, error: String(e.message ?? e) } : x))));
  };
  return (
    <div className="space-y-4 max-w-3xl">
      <div className="flex items-center justify-between gap-3 flex-wrap">
        <h1 className="text-xl font-bold">Ask about fraud alerts</h1>
        <div className="flex gap-2 flex-wrap"><PoweredBy>Cortex Agents</PoweredBy><PoweredBy>Semantic view</PoweredBy></div>
      </div>
      <div className="flex flex-wrap gap-2">
        {SAMPLE_QUESTIONS.map((s) => <button key={s} className="btn text-xs" disabled={busy} onClick={() => go(s)}>{s}</button>)}
      </div>
      {turns.map((t, i) => (
        <div key={i} className="space-y-2">
          <div className="card p-3 text-sm ml-auto max-w-[85%]" style={{ background: 'var(--accent-soft)' }}>{t.q}</div>
          {t.error ? <ErrorBox error={t.error} /> : !t.a ? <Reasoning kind="ask" /> : (
            <Card title="Answer" right={t.a.source === 'sample' ? <SampleAiBadge /> : <span className="text-[11px] muted">{(t.a.latencyMs / 1000).toFixed(1)} s · live</span>}>
              <Markdown text={t.a.text} />
              {t.a.sql && <details className="mt-3"><summary className="text-xs muted cursor-pointer">SQL generated by Cortex Analyst</summary>
                <pre className="text-[11px] rounded-lg p-3 mt-2 overflow-x-auto" style={{ background: 'var(--surface-2)' }}>{t.a.sql}</pre></details>}
            </Card>
          )}
        </div>
      ))}
      <form className="flex gap-2" onSubmit={(e) => { e.preventDefault(); go(q); }}>
        <input className="field" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Ask about alerts, merchants, channels, or rules" aria-label="Question" />
        <button className="btn btn-ai" disabled={busy} type="submit" aria-label="Ask"><Send className="w-4 h-4" aria-hidden /></button>
      </form>
      <p className="text-xs muted">The agent only reads the alerts semantic view. Answers describe this synthetic data set. AI-generated: check the numbers before acting.</p>
    </div>
  );
}
